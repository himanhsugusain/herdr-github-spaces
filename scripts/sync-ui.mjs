import { readFile, writeFile } from 'node:fs/promises';

// Herdr confines imports to each mod folder, so ship the shared code in each mod.
const source = await readFile(new URL('../mods/space-status/ui.js', import.meta.url), 'utf8');
const generated = '// Generated by scripts/sync-ui.mjs; edit mods/space-status/ui.js.\n' + source;
for (const name of ['agents-space', 'spaces-letter', 'github-spaces-status']) {
  const destination = new URL(`../mods/${name}/status.js`, import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(destination, 'utf8').catch(() => '') !== generated) {
      throw new Error(`${name}/status.js is out of date; run node scripts/sync-ui.mjs`);
    }
  } else {
    await writeFile(destination, generated);
  }
}
